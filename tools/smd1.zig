// ── CLI ────────────────────────────────────────────────────────────────────

const Cli = struct {
    goban: []const u8,
    out_path: []const u8,
    seed: u64 = 31337,
    sample: ?u32 = null,
    artifact: ?[]const u8 = null,
};

fn parseArgsDump(goban_opt: ?[]const u8, iter: *std.process.Args.Iterator) !Cli {
    const goban = goban_opt orelse return error.MissingGoban;
    const out_path = iter.next() orelse return error.MissingOutPath;
    var cli = Cli{ .goban = goban, .out_path = out_path };
    while (iter.next()) |arg| {
        if (std.mem.eql(u8, arg, "--seed")) {
            const v = iter.next() orelse return error.MissingValue;
            cli.seed = std.fmt.parseUnsigned(u64, v, 10) catch return error.BadValue;
        } else if (std.mem.eql(u8, arg, "--sample")) {
            const v = iter.next() orelse return error.MissingValue;
            cli.sample = std.fmt.parseUnsigned(u32, v, 10) catch return error.BadValue;
        } else if (std.mem.eql(u8, arg, "--artifact")) {
            const v = iter.next() orelse return error.MissingValue;
            cli.artifact = v;
        } else {
            return error.UnknownArg;
        }
    }
    return cli;
}

fn usageMsg() void {
    std.debug.print(
        \\usage: smd1 <goban> <out.smd1> [--seed S] [--sample N] [--artifact path]
        \\       smd1 verify <in.smd1> <goban>
        \\  goban: 2x2 | 3x2 | 3x3 | 4x4
        \\  2x2/3x2/3x3 -> exhaustive (every legal position, both sides).
        \\  4x4        -> sampled (default N=50000, seed=31337; 10 colex-decile
        \\                strata x 2 sides, 2500 per stratum-side).
        \\  --sample N : override the 4x4 sample size (must be a multiple of 20).
        \\  --artifact P: record SHA-256 of the WZO2 artifact in the sidecar.
        \\  verify    : load <in.smd1> and validate magic/version/goban/slice/CRC.
        \\
    , .{});
}

/// Parse "WxH" into (w, h). Returns null on malformed input.
fn parseGoban(s: []const u8) ?struct { w: usize, h: usize } {
    const x = std.mem.indexOfScalar(u8, s, 'x') orelse return null;
    const w = std.fmt.parseUnsigned(usize, s[0..x], 10) catch return null;
    const h = std.fmt.parseUnsigned(usize, s[x + 1 ..], 10) catch return null;
    if (w == 0 or h == 0) return null;
    return .{ .w = w, .h = h };
}

/// Compute the SHA-256 of a file. Reads the whole file (the 4x4 artifact is
/// 518 MB, well under the 4 GB runner cap) and hashes it — the same path
/// oracle_v2_accept uses to load the artifact. Returns null on failure so the
/// sidecar degrades gracefully (records null) instead of aborting the dump.
fn sha256File(io: std.Io, path: []const u8, gpa: std.mem.Allocator) ![32]u8 {
    const dir = std.Io.Dir.cwd();
    const bytes = dir.readFileAlloc(io, path, gpa, .unlimited) catch return error.OpenFailed;
    defer gpa.free(bytes);
    var digest: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(bytes, &digest, .{});
    return digest;
}

pub fn main(init: std.process.Init) !void {
    const io = init.io;
    const gpa = std.heap.page_allocator;

    var args_iter = std.process.Args.Iterator.init(init.minimal.args);
    const first = args_iter.next();
    _ = first; // binary name
    const sub = args_iter.next();

    // `smd1 verify <in.smd1> <goban>` — load + validate (acceptance #5).
    if (sub != null and std.mem.eql(u8, sub.?, "verify")) {
        const in_path = args_iter.next() orelse {
            usageMsg();
            std.debug.print("error: verify needs <in.smd1> <goban>\n", .{});
            std.process.exit(2);
        };
        const gstr = args_iter.next() orelse {
            usageMsg();
            std.debug.print("error: verify needs <in.smd1> <goban>\n", .{});
            std.process.exit(2);
        };
        const dims = parseGoban(gstr) orelse {
            usageMsg();
            std.debug.print("error: bad goban '{s}'\n", .{gstr});
            std.process.exit(2);
        };
        return runVerify(io, gpa, in_path, dims.w, dims.h);
    }

    // Default dump mode: <goban> <out.smd1> [opts]. Re-parse with the goban first.
    const cli = parseArgsDump(sub, &args_iter) catch |e| {
        usageMsg();
        std.debug.print("error: {s}\n", .{@errorName(e)});
        std.process.exit(2);
    };

    const dims = parseGoban(cli.goban) orelse {
        usageMsg();
        std.debug.print("error: bad goban '{s}'\n", .{cli.goban});
        std.process.exit(2);
    };

    // Artifact SHA-256 for the sidecar (optional provenance).
    var artifact_sha: ?[32]u8 = null;
    if (cli.artifact) |p| {
        artifact_sha = sha256File(io, p, gpa) catch |e| blk: {
            std.debug.print("warn: could not hash artifact '{s}': {s} (sidecar will record null)\n", .{ p, @errorName(e) });
            break :blk null;
        };
    }

    const out_dir = std.fs.path.dirname(cli.out_path) orelse "";
    if (out_dir.len > 0) {
        std.Io.Dir.cwd().createDirPath(io, out_dir) catch {};
    }

    const cwd = std.Io.Dir.cwd();

    if (dims.w == 2 and dims.h == 2) {
        try runExhaustive(2, 2, io, gpa, cwd, cli, artifact_sha);
    } else if (dims.w == 3 and dims.h == 2) {
        try runExhaustive(3, 2, io, gpa, cwd, cli, artifact_sha);
    } else if (dims.w == 3 and dims.h == 3) {
        try runExhaustive(3, 3, io, gpa, cwd, cli, artifact_sha);
    } else if (dims.w == 4 and dims.h == 4) {
        const n_total: u32 = cli.sample orelse 50000;
        try runSampled(4, 4, io, gpa, cwd, cli, artifact_sha, n_total);
    } else {
        usageMsg();
        std.debug.print("error: unsupported goban {d}x{d} (2x2, 3x2, 3x3, 4x4)\n", .{ dims.w, dims.h });
        std.process.exit(2);
    }
}

fn runVerify(io: std.Io, gpa: std.mem.Allocator, in_path: []const u8, w: usize, h: usize) !void {
    const cwd = std.Io.Dir.cwd();
    const bytes = cwd.readFileAlloc(io, in_path, gpa, .unlimited) catch |e| {
        std.debug.print("VERDICT: FATAL — cannot read '{s}': {s}\n", .{ in_path, @errorName(e) });
        std.process.exit(1);
    };
    defer gpa.free(bytes);
    const v = validate(bytes, w, h) catch |e| {
        std.debug.print("VERDICT: FAIL — '{s}' invalid: {s}\n", .{ in_path, @errorName(e) });
        std.process.exit(1);
    };
    std.debug.print("VERDICT: OK — '{s}' {d}x{d} records={d} colex_bytes={d} moves_bytes={d} slice=ko{d}/passes{d}\n", .{ in_path, w, h, v.record_count, v.cb, v.mb, SLICE_KO_NONE, SLICE_PASSES });
}

fn writeOut(io: std.Io, cwd: std.Io.Dir, path: []const u8, bytes: []const u8) !void {
    var file = try cwd.createFile(io, path, .{});
    defer file.close(io);
    try file.writePositionalAll(io, bytes, 0);
}

fn runExhaustive(
    comptime w: usize,
    comptime h: usize,
    io: std.Io,
    gpa: std.mem.Allocator,
    cwd: std.Io.Dir,
    cli: Cli,
    artifact_sha: ?[32]u8,
) !void {
    const t0 = nowMs();
    const res = try emitExhaustive(w, h, gpa);
    defer gpa.free(res.file);
    _ = validate(res.file, w, h) catch |e| {
        std.debug.print("FATAL: self-validation failed for {d}x{d}: {s}\n", .{ w, h, @errorName(e) });
        std.process.exit(1);
    };
    try writeOut(io, cwd, cli.out_path, res.file);
    // Sidecar.
    const sidecar = try buildExhaustiveSidecar(gpa, w, h, colexBytes(w * h), rules.Rules(w, h).moves_bytes, res.record_count, res.legal_count, cli.artifact, artifact_sha);
    defer gpa.free(sidecar);
    const sidecar_path = try std.fmt.allocPrint(gpa, "{s}.json", .{cli.out_path});
    defer gpa.free(sidecar_path);
    try writeOut(io, cwd, sidecar_path, sidecar);
    const dt = nowMs() - t0;
    std.debug.print("smd1 {d}x{d} exhaustive: {d} records ({d} legal positions x 2 sides) -> {s} ({d} bytes, {d} ms)\n", .{ w, h, res.record_count, res.legal_count, cli.out_path, res.file.len, dt });
    std.debug.print("smd1 sidecar -> {s}\n", .{sidecar_path});
}

fn runSampled(
    comptime w: usize,
    comptime h: usize,
    io: std.Io,
    gpa: std.mem.Allocator,
    cwd: std.Io.Dir,
    cli: Cli,
    artifact_sha: ?[32]u8,
    n_total: u32,
) !void {
    const t0 = nowMs();
    const res = try emitSampled(w, h, gpa, cli.seed, n_total, cli.artifact, artifact_sha);
    defer gpa.free(res.file);
    defer gpa.free(res.sidecar);
    _ = validate(res.file, w, h) catch |e| {
        std.debug.print("FATAL: self-validation failed for {d}x{d}: {s}\n", .{ w, h, @errorName(e) });
        std.process.exit(1);
    };
    try writeOut(io, cwd, cli.out_path, res.file);
    const sidecar_path = try std.fmt.allocPrint(gpa, "{s}.json", .{cli.out_path});
    defer gpa.free(sidecar_path);
    try writeOut(io, cwd, sidecar_path, res.sidecar);
    const dt = nowMs() - t0;
    std.debug.print("smd1 {d}x{d} sampled: {d} records (seed={d}, {d} strata x {d}/side) -> {s} ({d} bytes, {d} ms)\n", .{ w, h, res.record_count, cli.seed, 10, n_total / 20, cli.out_path, res.file.len, dt });
    std.debug.print("smd1 sidecar -> {s}\n", .{sidecar_path});
}

