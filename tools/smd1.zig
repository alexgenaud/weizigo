//
// SMD1 — solver-side move-set dump utility (T341, G3b pass0, plan §2.5/§5).
//
// Emits the SMD1 binary format defined in
//   docs/epic-01-markovian/sprints/verify-battery/pass0/design-M1.md §4.6
// (the authoritative contract: 28-byte header, sorted records, CRC-32
// ISO-HDLC, bit-per-cell move bitmap + pass bit, slice ko=NONE passes=0).
//
// The legal-move set in every record is generated by the KERNEL move
// generator (src/rules.zig, T339/MG-KERN) — NOT the solver's. This is the
// whole point of I11: the battery's independently-authored R8 move generator
// (src/vb_movegen.zig, T340) is compared, via SMD1, against the kernel. Using
// the solver's move generator here would defeat the independence (brief
// "Wrong answer" foreclosure #2).
//
// Slice. Every record is at the artifact slot: ko = NONE, passes = 0. The
// header records slice_ko = 255 (the SMD1 NONE sentinel — a format constant,
// distinct from the kernel's `ko >= n` convention) and slice_passes = 0.
// Move generation passes the kernel's ko_none (= n) so no point is ko-forbidden.
//
// Scope (plan §2.5/§3):
//   • 2x2, 3x2, 3x3 — EXHAUSTIVE: every legal position, both sides, in colex
//     order (records are sorted by (colex, side) by construction).
//   • 4x4 — SAMPLED: 50 000 states, stratified 25k Black / 25k White across
//     10 colex-decile strata (5 000 per stratum = 2 500 per stratum-side),
//     seed 31337. A `.smd1.json` sidecar records the seed, strata counts and
//     (when --artifact is given) the artifact SHA-256 for provenance.
//
// Module imports. This file is wired into the build graph by build.zig (the
// sprint console owns build.zig). The single named module "engine" is provided
// either by build.zig (addImport, rooted at src/smd1_engine.zig) or, for
// standalone `zig run`/`zig test` before wiring, by a -M flag:
//
//   @import("engine") -> src/smd1_engine.zig (re-exports rules, colex, enumerate)
//
// Standalone run (before build.zig wiring):
//   tools/runner -- zig run --dep engine -Mmain=tools/smd1.zig \
//       -Mengine=src/smd1_engine.zig -- <goban> <out.smd1> [--seed S]
//       [--sample N] [--artifact path]
//
// Standalone tests:
//   zig test --dep engine -Mmain=tools/smd1.zig -Mengine=src/smd1_engine.zig
//
// stdout = data (one summary line per dump: goban, mode, record_count, path),
// stderr = diagnostics (per util.note convention). Reference: src/util.zig.

const std = @import("std");
// The kernel move generator (rules), the colex indexer (colex) and the
// legal-position enumerator (enumerate) all live under src/ and are reached
// through the single "engine" re-export shim (src/smd1_engine.zig). Zig 0.16
// forbids a file in two modules, and rules.zig transitively imports
// colex.zig/enumerate.zig, so they cannot be separate module roots; the shim
// is the one module root that owns all three. See src/smd1_engine.zig.
const engine = @import("engine");
const rules = engine.rules;
const colex = engine.colex;
const enumerate = engine.enumerate;

// ── SMD1 format constants (design-M1 §4.6) ────────────────────────────────

const MAGIC = [_]u8{ 'S', 'M', 'D', '1' };
const VERSION: u8 = 1;
const HEADER_LEN: usize = 28;
/// SMD1 header sentinel for "no ko point at this slice". This is a FORMAT
/// constant (always 255 in the header), distinct from the kernel's runtime
/// `ko >= n` convention — the kernel's ko_none(= n) is what move generation
/// receives; 255 is what the header records.
const SLICE_KO_NONE: u8 = 255;
const SLICE_PASSES: u8 = 0;

const ValidateError = error{
    BadMagic,
    BadVersion,
    BadGoban,
    BadSlice,
    BadCrc,
    Truncated,
};

/// Monotonic milliseconds (std.time.milliTimestamp is gone in Zig 0.16).
fn nowMs() u64 {
    var ts: std.c.timespec = undefined;
    _ = std.c.clock_gettime(.MONOTONIC, &ts);
    return @as(u64, @intCast(ts.sec)) * 1000 + @as(u64, @intCast(ts.nsec)) / 1_000_000;
}

/// Bytes per colex index (design-M1 §4.6.2): 1 when 3^(w*h) ≤ 255; 4 up to
/// 4×3; 8 for 4×4. The supported gobans are 2×2, 3×2, 3×3, 4×3, 4×4.
fn colexBytes(n: usize) u8 {
    if (n <= 4) return 1; // 2x2: 3^4 = 81 ≤ 255
    if (n <= 12) return 4; // 3x2, 3x3, 4x3: up to 3^12 fits u32
    return 8; // 4x4 (spec mandates 8 even though 4 would suffice)
}

/// Write the low `nbytes` little-endian bytes of `val` into buf at `off`.
fn writeColexLE(buf: []u8, off: usize, val: u64, nbytes: u8) void {
    var i: usize = 0;
    while (i < nbytes) : (i += 1) {
        buf[off + i] = @intCast((val >> @intCast(i * 8)) & 0xFF);
    }
}

/// Append one SMD1 record (colex_idx | side | move_bitmap) to `buf`.
/// side_byte: 1 = Black to move, 2 = White to move (design-M1 §4.6.3).
fn appendRecord(
    buf: *std.ArrayListUnmanaged(u8),
    gpa: std.mem.Allocator,
    colex_idx: u64,
    side_byte: u8,
    bitmap: []const u8,
    cb: u8,
) !void {
    var rec: [12]u8 = undefined; // max = colex_bytes(8) + 1 + moves_bytes(3)
    const cbu: usize = cb;
    writeColexLE(&rec, 0, colex_idx, cb);
    rec[cbu] = side_byte;
    @memcpy(rec[cbu + 1 ..][0..bitmap.len], bitmap);
    try buf.appendSlice(gpa, rec[0 .. cbu + 1 + bitmap.len]);
}

/// Assemble the full SMD1 file: 28-byte header + records + trailing CRC-32.
/// The header's payload_crc32 field and the trailing 4-byte CRC are the same
/// value (CRC-32 ISO-HDLC of the records only — not the header).
fn assembleFile(
    gpa: std.mem.Allocator,
    w: usize,
    h: usize,
    cb: u8,
    mb: usize,
    record_count: u32,
    record_bytes: []const u8,
) ![]u8 {
    const total_len = HEADER_LEN + record_bytes.len + 4;
    const out = try gpa.alloc(u8, total_len);
    @memcpy(out[0..4], &MAGIC);
    out[4] = VERSION;
    out[5] = @intCast(w);
    out[6] = @intCast(h);
    out[7] = cb;
    out[8] = @intCast(mb);
    out[9] = 0;
    out[10] = 0;
    out[11] = 0; // reserved
    std.mem.writeInt(u32, out[12..16], record_count, .little);
    out[16] = SLICE_KO_NONE;
    out[17] = 0;
    out[18] = 0;
    out[19] = 0;
    out[20] = SLICE_PASSES;
    out[21] = 0;
    out[22] = 0;
    out[23] = 0;
    var crc = std.hash.crc.Crc32IsoHdlc.init();
    crc.update(record_bytes);
    const crc_val = crc.final();
    std.mem.writeInt(u32, out[24..28], crc_val, .little);
    @memcpy(out[HEADER_LEN..][0..record_bytes.len], record_bytes);
    std.mem.writeInt(u32, out[HEADER_LEN + record_bytes.len ..][0..4], crc_val, .little);
    return out;
}

/// Validate an SMD1 file: magic, version, goban, slice, length, and CRC-32
/// (both the header field and the trailing copy must match the recomputed
/// CRC of the records). Returns the parsed header fields on success.
fn validate(bytes: []const u8, w: usize, h: usize) ValidateError!struct {
    record_count: u32,
    cb: u8,
    mb: u8,
} {
    if (bytes.len < HEADER_LEN) return error.Truncated;
    if (!std.mem.eql(u8, bytes[0..4], &MAGIC)) return error.BadMagic;
    if (bytes[4] != VERSION) return error.BadVersion;
    if (bytes[5] != w or bytes[6] != h) return error.BadGoban;
    const cb = bytes[7];
    const mb: usize = bytes[8];
    if (bytes[9] != 0 or bytes[10] != 0 or bytes[11] != 0) return error.Truncated;
    const record_count = std.mem.readInt(u32, bytes[12..16], .little);
    if (bytes[16] != SLICE_KO_NONE or bytes[17] != 0 or bytes[18] != 0 or bytes[19] != 0)
        return error.BadSlice;
    if (bytes[20] != SLICE_PASSES or bytes[21] != 0 or bytes[22] != 0 or bytes[23] != 0)
        return error.BadSlice;
    const stored_crc = std.mem.readInt(u32, bytes[24..28], .little);
    const rec_len: usize = @as(usize, record_count) * (@as(usize, cb) + 1 + mb);
    if (bytes.len != HEADER_LEN + rec_len + 4) return error.Truncated;
    const record_bytes = bytes[HEADER_LEN..][0..rec_len];
    var crc = std.hash.crc.Crc32IsoHdlc.init();
    crc.update(record_bytes);
    if (crc.final() != stored_crc) return error.BadCrc;
    const trailing = std.mem.readInt(u32, bytes[HEADER_LEN + rec_len ..][0..4], .little);
    if (trailing != stored_crc) return error.BadCrc;
    return .{ .record_count = record_count, .cb = cb, .mb = @intCast(mb) };
}

const ExhaustiveResult = struct {
    file: []u8,
    record_count: u32,
    legal_count: u32,
};

/// Exhaustive dump for goban w×h: every legal position, both sides, at the
/// artifact slice (ko=NONE, passes=0). Records are emitted in colex-ascending
/// order with Black (1) before White (2) per position — i.e. already sorted
/// by (colex, side), so no explicit sort is needed.
fn emitExhaustive(comptime w: usize, comptime h: usize, gpa: std.mem.Allocator) !ExhaustiveResult {
    const R = rules.Rules(w, h);
    const X = colex.Indexer(w, h);
    const E = enumerate.Enumerator(w, h);
    const n = w * h;
    const cb = colexBytes(n);
    const mb = R.moves_bytes;
    const ko_none = R.ko_none();

    var records: std.ArrayListUnmanaged(u8) = .empty;
    defer records.deinit(gpa);

    var legal_count: u32 = 0;
    var idx: u64 = 0;
    while (idx < X.total) : (idx += 1) {
        const pos = X.pos_from_colex(idx);
        if (!E.is_legal(&pos)) continue;
        legal_count += 1;
        const bm_b = R.legalMoves(&pos, 1, ko_none, 0);
        try appendRecord(&records, gpa, idx, 1, bm_b[0..], cb);
        const bm_w = R.legalMoves(&pos, -1, ko_none, 0);
        try appendRecord(&records, gpa, idx, 2, bm_w[0..], cb);
    }
    const rec_size: usize = @as(usize, cb) + 1 + mb;
    const record_count: u32 = @intCast(records.items.len / rec_size);
    const file = try assembleFile(gpa, w, h, cb, mb, record_count, records.items);
    return .{ .file = file, .record_count = record_count, .legal_count = legal_count };
}

const StratumCount = struct {
    decile: usize,
    colex_lo: u64,
    colex_hi: u64,
    black: u32,
    white: u32,
};

const SampledResult = struct {
    file: []u8,
    sidecar: []u8,
    record_count: u32,
    strata: [10]StratumCount,
    legal_sampled: u32,
};

/// Stratified random sample for goban w×h (plan §3): `n_total` states split
/// across 10 colex-decile strata × 2 sides. Each stratum contributes
/// `n_total / 10` states = `n_total / 20` per stratum-side. `n_total` must be
/// a positive multiple of 20. Positions are rejection-sampled from the legal
/// positions whose colex falls in the stratum's decile range; a per-stratum-
/// side dedup set guarantees no duplicate (colex, side) record. Records are
/// sorted by (colex, side) before assembly.
fn emitSampled(
    comptime w: usize,
    comptime h: usize,
    gpa: std.mem.Allocator,
    seed: u64,
    n_total: u32,
    artifact_path: ?[]const u8,
    artifact_sha: ?[32]u8,
) !SampledResult {
    const R = rules.Rules(w, h);
    const X = colex.Indexer(w, h);
    const E = enumerate.Enumerator(w, h);
    const n = w * h;
    const cb = colexBytes(n);
    const mb = R.moves_bytes;
    const ko_none = R.ko_none();

    if (n_total == 0 or n_total % 20 != 0) return error.InvalidSampleSize;
    const n_per_stratum_side: u32 = n_total / 20;

    const Rec = struct { colex: u64, side: u8, bm: [mb]u8 };
    var recs: std.ArrayListUnmanaged(Rec) = .empty;
    defer recs.deinit(gpa);
    try recs.ensureTotalCapacity(gpa, n_total);

    var prng = std.Random.DefaultPrng.init(seed);
    const rnd = prng.random();

    var seen = std.AutoHashMap(u64, void).init(gpa);
    defer seen.deinit();

    var strata: [10]StratumCount = undefined;
    const total = X.total;
    const decile_width: u64 = total / 10;
    var legal_sampled: u32 = 0;

    for (0..10) |d| {
        const lo: u64 = @as(u64, d) * decile_width;
        const hi: u64 = if (d == 9) total else lo + decile_width;
        strata[d] = .{ .decile = d, .colex_lo = lo, .colex_hi = hi, .black = 0, .white = 0 };
        // Each side independently.
        inline for (.{ @as(i8, 1), @as(i8, -1) }) |side| {
            seen.clearRetainingCapacity();
            const side_byte: u8 = if (side > 0) 1 else 2;
            var got: u32 = 0;
            // Rejection-sample legal, not-yet-seen positions in [lo, hi).
            while (got < n_per_stratum_side) {
                const r = rnd.intRangeAtMost(u64, lo, hi - 1);
                const pos = X.pos_from_colex(r);
                if (!E.is_legal(&pos)) continue;
                if (seen.contains(r)) continue;
                try seen.put(r, {});
                const bm = R.legalMoves(&pos, side, ko_none, 0);
                try recs.append(gpa, .{ .colex = r, .side = side_byte, .bm = bm });
                got += 1;
                legal_sampled += 1;
            }
            if (side > 0) strata[d].black = got else strata[d].white = got;
        }
    }

    // Sort by (colex, side) ascending (design-M1 §4.6.1).
    std.mem.sort(Rec, recs.items, {}, struct {
        fn lt(_: void, a: Rec, b: Rec) bool {
            if (a.colex != b.colex) return a.colex < b.colex;
            return a.side < b.side;
        }
    }.lt);

    var records: std.ArrayListUnmanaged(u8) = .empty;
    defer records.deinit(gpa);
    for (recs.items) |r| {
        try appendRecord(&records, gpa, r.colex, r.side, r.bm[0..], cb);
    }
    const record_count: u32 = @intCast(recs.items.len);
    const file = try assembleFile(gpa, w, h, cb, mb, record_count, records.items);
    const sidecar = try buildSidecar(
        gpa,
        w,
        h,
        cb,
        mb,
        record_count,
        seed,
        n_total,
        n_per_stratum_side,
        &strata,
        artifact_path,
        artifact_sha,
    );
    return .{
        .file = file,
        .sidecar = sidecar,
        .record_count = record_count,
        .strata = strata,
        .legal_sampled = legal_sampled,
    };
}

fn hexSha256(hash: [32]u8) [64]u8 {
    const hex = "0123456789abcdef";
    var buf: [64]u8 = undefined;
    for (0..32) |i| {
        buf[i * 2] = hex[hash[i] >> 4];
        buf[i * 2 + 1] = hex[hash[i] & 0xF];
    }
    return buf;
}

/// Append a formatted string to `buf`, freeing the temporary allocPrint slice.
fn appendF(
    buf: *std.ArrayListUnmanaged(u8),
    gpa: std.mem.Allocator,
    comptime fmt: []const u8,
    args: anytype,
) !void {
    const s = try std.fmt.allocPrint(gpa, fmt, args);
    defer gpa.free(s);
    try buf.appendSlice(gpa, s);
}

/// Build the `.smd1.json` sidecar (design-M1 §4.6.7). For sampled dumps it
/// records the seed and per-stratum counts (brief acceptance #4); for
/// exhaustive dumps it records the mode and counts. The artifact SHA-256 is
/// included when supplied (--artifact) for provenance.
fn buildSidecar(
    gpa: std.mem.Allocator,
    w: usize,
    h: usize,
    cb: u8,
    mb: usize,
    record_count: u32,
    seed: u64,
    n_total: u32,
    n_per_stratum_side: u32,
    strata: *const [10]StratumCount,
    artifact_path: ?[]const u8,
    artifact_sha: ?[32]u8,
) ![]u8 {
    var buf: std.ArrayListUnmanaged(u8) = .empty;
    defer buf.deinit(gpa);
    try appendF(&buf, gpa, "{{\n", .{});
    try appendF(&buf, gpa, "  \"format\": \"SMD1\",\n", .{});
    try appendF(&buf, gpa, "  \"version\": {d},\n", .{VERSION});
    try appendF(&buf, gpa, "  \"goban\": \"{d}x{d}\",\n", .{ w, h });
    try appendF(&buf, gpa, "  \"w\": {d},\n  \"h\": {d},\n", .{ w, h });
    try appendF(&buf, gpa, "  \"mode\": \"sampled\",\n", .{});
    try appendF(&buf, gpa, "  \"record_count\": {d},\n", .{record_count});
    try appendF(&buf, gpa, "  \"colex_bytes\": {d},\n", .{cb});
    try appendF(&buf, gpa, "  \"moves_bytes\": {d},\n", .{mb});
    try appendF(&buf, gpa, "  \"slice_ko\": {d},\n", .{SLICE_KO_NONE});
    try appendF(&buf, gpa, "  \"slice_passes\": {d},\n", .{SLICE_PASSES});
    try appendF(&buf, gpa, "  \"slice\": \"ko=NONE, passes=0\",\n", .{});
    try appendF(&buf, gpa, "  \"seed\": {d},\n", .{seed});
    try appendF(&buf, gpa, "  \"sample_size\": {d},\n", .{n_total});
    try appendF(&buf, gpa, "  \"n_per_stratum_side\": {d},\n", .{n_per_stratum_side});
    try appendF(&buf, gpa, "  \"sampling_frame\": \"legal positions (OEIS A094777 for square gobans; {d}x{d} rectangular)\",\n", .{ w, h });
    try appendF(&buf, gpa, "  \"generator\": \"kernel (src/rules.zig, T339/MG-KERN)\",\n", .{});
    try appendF(&buf, gpa, "  \"strata\": [\n", .{});
    for (strata, 0..) |s, i| {
        try appendF(&buf, gpa, "    {{\"decile\": {d}, \"colex_lo\": {d}, \"colex_hi\": {d}, \"black\": {d}, \"white\": {d}}}{s}\n", .{
            s.decile, s.colex_lo, s.colex_hi, s.black, s.white, if (i + 1 < 10) "," else "",
        });
    }
    try appendF(&buf, gpa, "  ],\n", .{});
    if (artifact_path) |p| {
        try appendF(&buf, gpa, "  \"artifact_path\": \"{s}\",\n", .{p});
        if (artifact_sha) |sha| {
            try appendF(&buf, gpa, "  \"artifact_sha256\": \"{s}\"\n", .{hexSha256(sha)});
        } else {
            try appendF(&buf, gpa, "  \"artifact_sha256\": null\n", .{});
        }
    } else {
        try appendF(&buf, gpa, "  \"artifact_path\": null,\n", .{});
        try appendF(&buf, gpa, "  \"artifact_sha256\": null\n", .{});
    }
    try appendF(&buf, gpa, "}}\n", .{});
    return try buf.toOwnedSlice(gpa);
}

